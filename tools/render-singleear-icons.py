#!/usr/bin/env python3
"""Render the original earphone glyphs into LVGL alpha masks. Requires ImageMagick.
Run: python3 tools/render-singleear-icons.py > sonix-player/src/gui/shell/singleear_icons.c
"""
import subprocess

# Left earphone, mirrored for the right. The stereo glyph shows both.
EAR = '<path d="M10 22v-5a6 6 0 0 1 12 0v4c0 2-2 4-4 4h-1v6a3 3 0 0 1-6 0v-9z"/>'

def render(left, right):
    svg = '<svg xmlns="http://www.w3.org/2000/svg" width="48" height="48" viewBox="0 0 48 48"><g fill="none" stroke="white" stroke-width="3" stroke-linejoin="round">'
    if left:
        svg += EAR
    if right:
        svg += '<g transform="translate(48 0) scale(-1 1)">' + EAR + '</g>'
    svg += '</g></svg>'
    return subprocess.check_output(['magick', '-background', 'none', '-density', '384', 'svg:-',
                                    '-resize', '48x48', '-alpha', 'extract', '-depth', '8', 'gray:-'], input=svg.encode())

print('/* Generated by tools/render-singleear-icons.py. */\n#include "icons.h"')
for name, left, right in [('stereo', True, True), ('left', True, False), ('right', False, True)]:
    data = render(left, right)
    assert len(data) == 48 * 48
    symbol = 'icon_singleear_' + name
    print(f'\nstatic const uint8_t {symbol}_data[] = {{')
    for start in range(0, len(data), 24):
        print('\t' + ', '.join(map(str, data[start:start + 24])) + ',')
    print(f'''}};
const lv_image_dsc_t {symbol} = {{
    .header = {{.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8, .w = 48, .h = 48, .stride = 48}},
    .data_size = sizeof({symbol}_data), .data = {symbol}_data,
}};''')
